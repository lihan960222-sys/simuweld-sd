import {test, expect} from '@playwright/test';

test('模型树、信息弹窗、两侧宽度和模型替换',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/#token='+process.env.SFMARC_TEST_TOKEN);
  await expect(page.locator('#tool-model')).toHaveText('模型查看');
  await expect(page.locator('.units')).toHaveCount(0);
  await page.locator('#open-model').click();
  await page.locator('#import-units').selectOption('mm');
  await page.locator('#file').setInputFiles('work/geometry-tests/two_blocks.inp');
  await expect(page.locator('.body-card')).toHaveCount(2);
  await expect(page.locator('#busy')).toBeHidden();
  await expect(page.locator('#open-model')).toHaveAccessibleName('删除并重新上传');
  await expect(page.locator('#model-info')).toBeHidden();
  await page.locator('#model-info-button').hover();
  await expect(page.locator('#model-info')).toBeVisible();
  const popup=await page.locator('#model-info').boundingBox(),sidebar=await page.locator('aside.left').boundingBox();
  expect(popup!.x).toBeGreaterThanOrEqual(sidebar!.x);
  expect(popup!.x+popup!.width).toBeLessThanOrEqual(sidebar!.x+sidebar!.width);
  await page.locator('#tool-model').hover();
  await expect(page.locator('#model-info')).toBeHidden();
  await page.locator('#model-info-button').click();
  await page.locator('#tool-model').hover();
  await expect(page.locator('#model-info')).toBeVisible();
  await page.locator('#tool-model').click();
  await expect(page.locator('#model-info')).toBeHidden();
  await page.locator('#resize-left').focus();
  for(let i=0;i<4;i++) await page.keyboard.press('ArrowLeft');
  await expect(page.locator('#resize-left')).toHaveAttribute('aria-valuenow','190');
  await page.locator('#model-info-button').hover();
  const narrowPopup=await page.locator('#model-info').boundingBox(),narrowSidebar=await page.locator('aside.left').boundingBox();
  expect(narrowPopup!.x).toBeGreaterThanOrEqual(narrowSidebar!.x);
  expect(narrowPopup!.x+narrowPopup!.width).toBeLessThanOrEqual(narrowSidebar!.x+narrowSidebar!.width);
  await page.locator('#tool-model').hover();
  const volumes=await page.locator('.body-volume').allTextContents();
  expect(volumes).toEqual(['1,000 mm³','24 mm³']);
  await page.getByLabel('全部实体显示',{exact:true}).uncheck();
  await expect(page.locator('[data-body-visible]:checked')).toHaveCount(0);
  await expect(page.locator('#all-bodies')).toHaveCount(0);
  await page.getByLabel('全部实体显示',{exact:true}).check();
  await expect(page.locator('[data-body-visible]:checked')).toHaveCount(2);
  await page.locator('#projection').selectOption('orthographic');
  await page.locator('#render-mode').selectOption('solid-edges');
  await page.locator('#explode').click();
  await page.locator('#explosion').fill('60');
  await expect(page.locator('#explosion-value')).toHaveText('60%');
  const before=await page.locator('.workspace').boundingBox();
  const handle=await page.locator('#resize-left').boundingBox();
  await page.mouse.move(handle!.x+3,handle!.y+200);await page.mouse.down();
  await page.mouse.move(handle!.x+83,handle!.y+200,{steps:8});await page.mouse.up();
  await expect.poll(async()=>Math.round((await page.locator('.workspace').boundingBox())!.width)).toBe(Math.round(before!.width-80));
  await page.locator('#tool-welding').click();
  await expect(page.locator('#explosion-control')).toBeHidden();
  const rightBefore=await page.locator('.workspace').boundingBox();
  await page.locator('#resize-right').focus();await page.keyboard.press('ArrowLeft');
  await expect.poll(async()=>Math.round((await page.locator('.workspace').boundingBox())!.width)).toBe(Math.round(rightBefore!.width-16));
  expect(await page.locator('#viewport canvas').evaluate(element=>Math.abs(element.clientWidth-element.getBoundingClientRect().width))).toBeLessThan(1);
  await page.locator('#open-model').click();await expect(page.locator('#model-dialog')).toBeVisible();
  await page.locator('#close-model-dialog').click();
  await expect(page.locator('.body-card')).toHaveCount(0);
  await expect(page.locator('#open-model')).toHaveAccessibleName('打开模型');
  expect(errors).toEqual([]);
});

test('米制 DAT 的面积显示为平方毫米，载荷保留文件单位',async({page})=>{
  test.skip(!process.env.SFMARC_TEST_PAIR_DAT,'需要指定真实米制 DAT');
  await page.goto('/#token='+process.env.SFMARC_TEST_TOKEN);
  await page.locator('#open-model').click();
  await page.locator('#import-units').selectOption('m');
  await page.locator('#file').setInputFiles(process.env.SFMARC_TEST_PAIR_DAT!);
  await expect(page.locator('#busy')).toBeHidden({timeout:90000});
  await expect(page.locator('.body-card')).not.toHaveCount(0);
  await page.locator('#tool-surface-load').click();
  await page.locator('[data-view=xy]').click();
  const canvas=page.locator('#viewport canvas'),box=(await canvas.boundingBox())!;
  for(const x of [.5,.4,.6,.3,.7]) {
    await canvas.click({position:{x:box.width*x,y:box.height*.5}});
    await expect(page.locator('#busy')).toBeHidden();
    if(Number(await page.locator('#selected-count').textContent())>0) break;
  }
  await expect.poll(async()=>Number(await page.locator('#selected-count').textContent())).toBeGreaterThan(0);
  const response=page.waitForResponse(response=>response.url().endsWith('/api/preview'));
  await page.locator('#magnitude').dispatchEvent('change');
  const preview=await(await response).json();
  expect(preview.pressure).toBe(1e6);
  expect(preview.area_unit).toBe('m²');
  const area=new Intl.NumberFormat('zh-CN',{maximumSignificantDigits:5}).format(preview.area*1e6);
  await expect(page.locator('#area-info')).toHaveText(area+' mm²');
  await expect(page.locator('#force-info')).toContainText('N');
  await page.locator('#save-load').click();
  const exportRequest=page.waitForRequest(request=>request.url().endsWith('/api/export'));
  const download=page.waitForEvent('download');await page.locator('#export').click();
  expect((await exportRequest).postDataJSON().loads[0].length_unit).toBe('m');await download;
});
