      MODULE KSDDATA
      IMPLICIT NONE
      INTEGER KCOUNT,KMAXPASS
      INTEGER,ALLOCATABLE :: KID(:),KPOINT(:),KHEAD(:),KNEXT(:)
      DOUBLE PRECISION,ALLOCATABLE :: KT(:,:),KH(:),KN(:,:)
      DOUBLE PRECISION,ALLOCATABLE :: KM(:,:),KC(:,:)
      END MODULE KSDDATA

      SUBROUTINE UEXTERNALDB(LOP,LRESTART,TIME,DTIME,KSTEP,KINC)
      USE KSDDATA
      INCLUDE 'ABA_PARAM.INC'
      DIMENSION TIME(2)
      CHARACTER*1024 OUTDIR
      CHARACTER*80 INSTANCE
      INTEGER LOUT,IOS,I,JRC,LOCALID,MAXID
      IF (LOP.NE.0.AND.LOP.NE.4) RETURN
      IF (ALLOCATED(KID)) THEN
         DEALLOCATE(KID,KPOINT,KHEAD,KNEXT,KT,KH,KN,KM,KC)
      END IF
      CALL GETOUTDIR(OUTDIR,LOUT)
      OPEN(UNIT=101,FILE=OUTDIR(1:LOUT)//'/SD_LOAD_DATA.txt',
     1 STATUS='OLD',ACTION='READ',IOSTAT=IOS)
      IF (IOS.NE.0) THEN
         WRITE(7,*) 'SD: cannot open SD_LOAD_DATA.txt'
         CALL KSDABORT('SD: cannot open loading data')
      END IF
      READ(101,*,IOSTAT=IOS) KCOUNT,KMAXPASS
      IF (IOS.NE.0.OR.KCOUNT.LE.0.OR.KMAXPASS.LE.0)
     1    CALL KSDABORT('SD: invalid loading data header')
      ALLOCATE(KID(KCOUNT),KPOINT(KCOUNT),KNEXT(KCOUNT))
      ALLOCATE(KT(2,KCOUNT),KH(KCOUNT),KN(3,KCOUNT))
      ALLOCATE(KM(6,KCOUNT),KC(6,KCOUNT))
      DO I=1,KCOUNT
         READ(101,'(A)',IOSTAT=IOS) INSTANCE
         IF (IOS.NE.0) CALL KSDABORT('SD: missing instance name')
         READ(101,*,IOSTAT=IOS) LOCALID,KPOINT(I),KT(:,I),
     1       KH(I),KN(:,I),KM(:,I),KC(:,I)
         IF (IOS.NE.0.OR.KT(2,I).LE.KT(1,I))
     1       CALL KSDABORT('SD: invalid loading event')
         CALL GETINTERNAL(INSTANCE,LOCALID,1,KID(I),JRC)
         IF (JRC.NE.0.OR.KID(I).LE.0) THEN
            WRITE(7,*) 'SD: element lookup failed ',LOCALID
            CALL KSDABORT('SD: element lookup failed')
         END IF
      END DO
      CLOSE(101)
      MAXID=MAXVAL(KID)
      IF (MAXID.GT.20000000)
     1    CALL KSDABORT('SD: internal element index exceeds limit')
      ALLOCATE(KHEAD(MAXID))
      KHEAD=0
      DO I=1,KCOUNT
         KNEXT(I)=KHEAD(KID(I))
         KHEAD(KID(I))=I
      END DO
      END

      SUBROUTINE KSDABORT(MESSAGE)
      IMPLICIT NONE
      CHARACTER*(*) MESSAGE
      INTEGER INTV(1)
      DOUBLE PRECISION REALV(1)
      CHARACTER*8 CHARV(1)
      INTV=0
      REALV=0.D0
      CHARV=' '
      CALL STDB_ABQERR(-3,MESSAGE,INTV,REALV,CHARV)
      END

      SUBROUTINE USDFLD(FIELD,STATEV,PNEWDT,DIRECT,T,CELENT,
     1 TIME,DTIME,CMNAME,ORNAME,NFIELD,NSTATV,NOEL,NPT,LAYER,
     2 KSPT,KSTEP,KINC,NDI,NSHR,COORD,JMAC,JMATYP,MATLAYO,LACCFLA)
      USE KSDDATA
      INCLUDE 'ABA_PARAM.INC'
      CHARACTER*80 CMNAME,ORNAME
      DIMENSION FIELD(NFIELD),STATEV(NSTATV),DIRECT(3,3),T(3,3)
      DIMENSION TIME(2),COORD(*),JMAC(*),JMATYP(*)
      DIMENSION EG(3,3),EL(3,3),V(6)
      INTEGER ROW,SLOT,OFFSET,I,J
      DOUBLE PRECISION Z
      IF (STATEV(1).GE.1.D0) RETURN
      IF (.NOT.ALLOCATED(KHEAD)) CALL XIT
      IF (KSPT.LT.1.OR.KSPT.GT.5.OR.LAYER.GT.1) CALL XIT
      IF (NSTATV.LT.1+5*KMAXPASS) CALL XIT
      SLOT=0
      ROW=0
      IF (NOEL.LE.SIZE(KHEAD)) ROW=KHEAD(NOEL)
      DO WHILE (ROW.GT.0)
         IF (KPOINT(ROW).EQ.NPT) THEN
            SLOT=SLOT+1
            IF (SLOT.GT.KMAXPASS) CALL XIT
            Z=(KSPT-3)*0.25D0*KH(ROW)*
     1        DOT_PRODUCT(DIRECT(:,3),KN(:,ROW))
            V=KM(:,ROW)+Z*KC(:,ROW)
            EG=0.D0
            EG(1,1)=V(1)
            EG(2,2)=V(2)
            EG(3,3)=V(3)
            EG(1,2)=V(4)
            EG(2,1)=V(4)
            EG(1,3)=V(5)
            EG(3,1)=V(5)
            EG(2,3)=V(6)
            EG(3,2)=V(6)
            EL=MATMUL(TRANSPOSE(DIRECT),MATMUL(EG,DIRECT))
            OFFSET=2+5*(SLOT-1)
            STATEV(OFFSET)=KT(1,ROW)
            STATEV(OFFSET+1)=KT(2,ROW)
            STATEV(OFFSET+2)=EL(1,1)
            STATEV(OFFSET+3)=EL(2,2)
            STATEV(OFFSET+4)=2.D0*EL(1,2)
         END IF
         ROW=KNEXT(ROW)
      END DO
      STATEV(1)=SLOT+1
      END

      SUBROUTINE UEXPAN(EXPAN,DEXPANDT,TEMP,TIME,DTIME,PREDEF,
     1 DPRED,STATEV,CMNAME,NSTATV,NOEL)
      INCLUDE 'ABA_PARAM.INC'
      CHARACTER*80 CMNAME
      DIMENSION EXPAN(*),DEXPANDT(*),TEMP(2),TIME(2),PREDEF(*)
      DIMENSION DPRED(*),STATEV(NSTATV)
      DOUBLE PRECISION KSDRAMP,FRACTION,FIRST,LAST
      INTEGER SLOT,OFFSET,I,COUNT
      IF (STATEV(1).LT.1.D0) THEN
         WRITE(7,*) 'SD: USDFLD state not initialized'
         CALL XIT
      END IF
      DO I=1,3
         EXPAN(I)=0.D0
         DEXPANDT(I)=0.D0
      END DO
      COUNT=NINT(STATEV(1))-1
      DO SLOT=1,COUNT
         OFFSET=2+5*(SLOT-1)
         FIRST=STATEV(OFFSET)
         LAST=STATEV(OFFSET+1)
         FRACTION=KSDRAMP(TIME(2),FIRST,LAST)-
     1       KSDRAMP(TIME(2)-DTIME,FIRST,LAST)
         DO I=1,3
            EXPAN(I)=EXPAN(I)+FRACTION*STATEV(OFFSET+1+I)
         END DO
      END DO
      END

      DOUBLE PRECISION FUNCTION KSDRAMP(TIME,FIRST,LAST)
      IMPLICIT NONE
      DOUBLE PRECISION TIME,FIRST,LAST,X
      IF (LAST.LE.FIRST) CALL XIT
      X=MAX(0.D0,MIN(1.D0,(TIME-FIRST)/(LAST-FIRST)))
      KSDRAMP=X*X*(3.D0-2.D0*X)
      END
